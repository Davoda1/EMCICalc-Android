#!/usr/bin/env python3
"""Generate and verify the value-metadata help dictionary (no network needed)."""
import argparse
from collections import Counter
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
DOCS = ROOT / 'docs/translation-inputs'
HEADER = ROOT / 'src/financemetadatatranslations.h'
LOCALES = ['hu', 'de', 'fr', 'es', 'it', 'ru', 'zh', 'ja']


def source_keys():
    source = (ROOT / 'src/finance_functions.cpp').read_text().split('QMap<QString, FunctionMetadata> financeFunctionMetadata()')[1]
    literal = r'"((?:[^"\\]|\\.)*)"'
    keys = set()
    for match in re.finditer(r'argument\(' + literal + r',\s*' + literal + r',\s*' + literal + r',\s*' + literal + r'(?:,\s*' + literal + r')?', source):
        keys.update([match[2], match[3], match[5] or 'Finite real number'])
    for match in re.finditer(r'add\(' + literal + r',\s*\d+,\s*' + literal, source):
        keys.add(match[2])
    keys.update([
        'Expression', 'Argument %1', "No additional argument restrictions are supplied by this function's engine metadata.",
        'Vertical coordinate; supplied first. Y and X cannot both be zero.',
        'Horizontal coordinate; supplied second. Result uses the selected angle unit.',
        'Data or X values',
        'One vector of Y samples at X=1,2,…; or a two-column X/Y matrix; or X values when the optional Y vector is supplied.',
        'Optional Y vector matching the X vector. Omit it (default []) for sequential samples or a two-column matrix.',
        'Parameter %1 of the saved pure function %2.'
    ])
    return sorted(keys)


def generate():
    keys = source_keys()
    inventory = json.loads((DOCS / 'finance-metadata-translation-keys.json').read_text())
    assert keys == inventory, 'Translation key inventory differs from current finance metadata'
    west = json.loads((DOCS / 'finance-metadata-translations-west.json').read_text())
    east = json.loads((DOCS / 'finance-metadata-translations-east.json').read_text())
    assert set(west) == set(east) == set(keys), 'Missing or obsolete translation keys'
    dictionary = {}
    for key in keys:
        rows = west[key] + east[key]
        assert len(rows) == 8, ('Wrong locale count', key)
        for locale, text in zip(LOCALES, rows):
            assert isinstance(text, str) and text.strip(), ('Empty translation', locale, key)
            assert sorted(re.findall(r'%[1-9]', key)) == sorted(re.findall(r'%[1-9]', text)), ('Changed placeholders', locale, key)
            # Genuine short cognates may match (e.g. French 'Inflation'); full
            # prose must be translated, not marked localized by copying English.
            if len(key.split()) >= 5:
                assert key != text, ('English prose fallback', locale, key)
            # Canonical function syntax/examples and numerical constraints must
            # retain their numeric values. Different natural-language order is OK.
            numbers = lambda value: Counter(re.findall(r'(?<![A-Za-z0-9])[-+]?\d+(?:\.\d+)?', value))
            assert not (numbers(key) - numbers(text)), ('Changed numeric example or bound', locale, key)
        dictionary[key] = rows
    encoded = json.dumps(dictionary, ensure_ascii=False, indent=2)
    return '''// SPDX-License-Identifier: MIT
// Generated by scripts/generate_finance_metadata_translations.py.
// Columns: hu, de, fr, es, it, ru, zh, ja. Canonical identifiers stay unchanged.
#pragma once
#include <QJsonArray>
#include <QJsonDocument>
#include <QJsonObject>
#include <QRegularExpression>
#include <QStringList>

inline QString financeMetadataTranslate(const QString &language, const char *english) {
    static const QStringList locales{"hu", "de", "fr", "es", "it", "ru", "zh", "ja"};
    const int column = locales.indexOf(language.toLower().replace('-', '_').section('_', 0, 0));
    if (column < 0) return {};
    static const QJsonObject dictionary = QJsonDocument::fromJson(R"EMCIFINTR(
''' + encoded + '''
)EMCIFINTR").object();
    const QString input = QString::fromUtf8(english);
    const auto translated = [&](const QString &key) {
        const auto row = dictionary.value(key).toArray();
        return row.size() == 8 ? row.at(column).toString() : QString();
    };
    QString result = translated(input);
    if (!result.isEmpty()) return result;
    // These values are rendered by the worker before crossing the UI boundary;
    // translate the sentence while preserving user-chosen parameter identifiers.
    static const QRegularExpression argument(QStringLiteral("^Argument ([0-9]+)$"));
    static const QRegularExpression parameter(QStringLiteral("^Parameter (.+) of the saved pure function (.+)\\\\.$"));
    auto match = argument.match(input);
    if (match.hasMatch()) return translated(QStringLiteral("Argument %1")).arg(match.captured(1));
    match = parameter.match(input);
    if (match.hasMatch()) return translated(QStringLiteral("Parameter %1 of the saved pure function %2.")).arg(match.captured(1), match.captured(2));
    return {};
}
''', len(keys)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    options = parser.parse_args()
    generated, count = generate()
    if options.check:
        assert HEADER.exists() and HEADER.read_text() == generated, 'Generated header is stale'
        print(f'PASS: {count} current keys x 8 locales; placeholders, numeric constraints, translated prose, and generated header verified')
    else:
        HEADER.write_text(generated)
        print(f'Generated {HEADER.name}: {count} keys x 8 locales')


if __name__ == '__main__':
    main()
